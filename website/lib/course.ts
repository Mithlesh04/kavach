/** URL slug from a title: "If...Else" → "if-else", "ask<T>" → "ask", "C++" → "cpp". */
export function slugOf(title: string): string {
  return title
    .toLowerCase()
    .replace(/\+\+/g, "pp")
    .replace(/&/g, " and ")
    .replace(/<[^>]*>/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

