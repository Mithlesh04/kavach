//! Which op carries out each standard library function that maps to one
//! op, its arguments as they are (spec 14). Functions that need more work
//! (`json`, `time.sleep`, `crypto`, TLS) are lowered in `lower_std.rs`.

use crate::rt_op::RtOp;

/// The op for `module.name`, if it is one of these.
pub(crate) fn std_op(module: &str, name: &str) -> Option<RtOp> {
    Some(match (module, name) {
        ("fs", "read_text") => RtOp::FsReadText,
        ("fs", "write_text") => RtOp::FsWriteText,
        ("fs", "append_text") => RtOp::FsAppendText,
        ("fs", "exists") => RtOp::FsExists,
        ("fs", "read_bytes") => RtOp::FsReadBytes,
        ("fs", "lines") => RtOp::FsLines,
        ("net", "listen") => RtOp::NetListen,
        ("net", "connect") => RtOp::NetConnect,
        ("net", "connect_quic") => RtOp::NetConnectQuic,
        ("net", "bind") => RtOp::NetBind,
        ("fs", "chunks") => RtOp::FsChunks,
        ("fs", "write_bytes") => RtOp::FsWriteBytes,
        ("fs", "write_durable") => RtOp::FsWriteDurable,
        ("fs", "list") => RtOp::FsList,
        ("fs", "remove") => RtOp::FsRemove,
        ("fs", "create_dir") => RtOp::FsCreateDir,
        ("fs", "stat") => RtOp::FileInfoStat,
        ("fs", "set_read_only") => RtOp::FileInfoSetReadOnly,
        ("fs", "set_permissions") => RtOp::FileInfoSetPermissions,
        ("fs", "rename") => RtOp::FileInfoRename,
        ("fs", "symlink") => RtOp::FileInfoSymlink,
        ("fs", "copy") => RtOp::FileInfoCopy,
        ("fs", "remove_all") => RtOp::FileInfoRemoveAll,
        ("time", "now_ms") => RtOp::TimeNowMs,
        ("time", "monotonic_ms") => RtOp::TimeMonotonicMs,
        ("time", "sleep_ms") => RtOp::TimeSleepMs,
        ("time", "zone_offset") => RtOp::ZoneOffset,
        ("agents", "call_key") => RtOp::JournalCallKey,
        ("agents", "request_fields") => RtOp::AgentApprovals,
        ("agents", "answer_request") => RtOp::AgentAnswer,
        ("crypto", "ed25519_verify") => RtOp::CryptoEd25519Verify,
        ("crypto", "p256_verify") => RtOp::CryptoP256Verify,
        ("window", "open_id") => RtOp::WindowOpen,
        ("window", "events_id") => RtOp::WindowEvents,
        ("window", "texts_id") => RtOp::WindowTexts,
        ("window", "size_id") => RtOp::WindowSize,
        ("window", "scale_id") => RtOp::WindowScale,
        ("window", "listen_id") => RtOp::WindowListen,
        ("window", "set_title_id") => RtOp::WindowTitle,
        ("window", "set_fullscreen_id") => RtOp::WindowFullscreen,
        ("window", "lock_cursor_id") => RtOp::WindowLockCursor,
        ("window", "close_id") => RtOp::WindowClose,
        ("process", "start_id") => RtOp::RunStart,
        ("process", "next_id") => RtOp::RunNext,
        ("process", "exit_id") => RtOp::RunExit,
        ("process", "kill_id") => RtOp::RunKill,
        ("process", "close_id") => RtOp::RunClose,
        ("process", "peak_bytes_id") => RtOp::RunPeak,
        ("gpu", "screen_id") => RtOp::DrawScreen,
        ("gpu", "frame_id") => RtOp::DrawFrame,
        ("gpu", "clear_id") => RtOp::DrawClear,
        ("gpu", "show_id") => RtOp::DrawShow,
        ("gpu", "drop_frame_id") => RtOp::DrawDropFrame,
        ("gpu", "close_id") => RtOp::DrawClose,
        ("log", "metric_id") => RtOp::OtlpMetric,
        ("log", "trace_id_text") => RtOp::ScopeTraceId,
        ("log", "traceparent_text") => RtOp::ScopeTraceparent,
        ("log", "name_span_id") => RtOp::ScopeRename,
        ("fs", "writer_open_id") => RtOp::FsWriterOpen,
        ("fs", "writer_write_id") => RtOp::FsWriterWrite,
        ("fs", "writer_finish_id") => RtOp::FsWriterFinish,
        ("fs", "writer_close_id") => RtOp::FsWriterClose,
        ("compress", "encode_bytes") => RtOp::CompressEncode,
        ("compress", "decode_bytes") => RtOp::CompressDecode,
        ("clipboard", "read_text") => RtOp::ClipReadText,
        ("clipboard", "write_text") => RtOp::ClipWriteText,
        ("devices", "serial_ports") => RtOp::SerialPorts,
        ("devices", "open_serial_id") => RtOp::SerialOpen,
        ("devices", "read_serial") => RtOp::SerialRead,
        ("devices", "write_serial") => RtOp::SerialWrite,
        ("devices", "close_serial") => RtOp::SerialClose,
        ("math", "sqrt") => RtOp::MathSqrt,
        ("math", "pow") => RtOp::MathPow,
        ("math", "floor") => RtOp::MathFloor,
        ("math", "ceil") => RtOp::MathCeil,
        ("math", "round") => RtOp::MathRound,
        ("io", "read_line") => RtOp::IoReadLine,
        ("io", "read_hidden") => RtOp::IoReadHidden,
        ("io", "is_terminal") => RtOp::IoIsTerminal,
        ("io", "colors") => RtOp::IoColors,
        ("io", "write") => RtOp::IoWrite,
        ("cli", "args") => RtOp::CliArgs,
        ("cli", "exit") => RtOp::CliExit,
        ("cli", "stop_hold") => RtOp::CliStopHold,
        ("cli", "stop_asked") => RtOp::CliStopAsked,
        ("cli", "stop_done") => RtOp::CliStopDone,
        ("regex", "new") => RtOp::RegexNew,
        ("regex", "advanced") => RtOp::RegexAdvanced,
        _ => return None,
    })
}
