//! `chip.svd`, a chip written by hand, made into a module (spec 6.5):
//! it compiles, and each field's mask and shift are its bits. Running
//! the module on memory of its own is in `tools/cli/tests/registers.rs`.

const CHIP: &str = include_str!("chip.svd");

fn module() -> String {
    kavach_svd::generate(CHIP, "chip.svd").expect("the chip is read")
}

#[test]
fn the_module_compiles() {
    let main = "\nfn main() {\n    unsafe {\n        const mem: Ptr<UInt8> = alloc(128)\n        const gpio = Gpioa.at(mem)\n        gpio.set_moder_moder5(1)\n        print(gpio.moder_moder5())\n        print(Uart1.at(mem).ch1_en())\n        print(gpiob_address)\n        free(mem)\n    }\n}\n";
    let src = module() + main;
    let options = kavach_driver::Options {
        allow_unsafe: true,
        ..Default::default()
    };
    let c = kavach_driver::compile(&src, "main.kav", options);
    let said: Vec<String> = c.messages.iter().map(|m| m.text.clone()).collect();
    assert!(said.is_empty(), "{said:#?}\n{src}");
}

#[test]
fn fields_are_masked_and_shifted_by_their_bits() {
    let m = module();
    for line in [
        "// Generated by kavach svd from chip.svd: make it again rather than change it.",
        "pub const gpioa_address = 0x4800_0000",
        "pub const gpiob_address = 0x4800_0400",
        "pub const uart_1_address = 0x4000_4400",
        "/// General-purpose I/O & pins",
        "/// `Gpioa.at(p)` makes it, in `unsafe`: `p` is `Ptr.at(gpioa_address)` on the chip. Also for GPIOB.",
        "    /// MODER: Mode register (offset 0x0, 32 bits).",
        "        unsafe { self.ptr32(0x0).read_volatile() }",
        "        unsafe { self.ptr32(0x0).write_volatile(v) }",
        // Bits 10–11.
        "        (self.moder() & 0xc00) >> 10",
        "        require v <= 0x3",
        "        self.set_moder((self.moder() & 0xffff_f3ff) | (v << 10))",
        // Bits 0–1: no shift.
        "        self.moder() & 0x3",
        "        self.set_moder((self.moder() & 0xffff_fffc) | v)",
        // A one-bit field is a Bool.
        "    pub fn idr_idr5(self) -> Bool {",
        "        (self.idr() & 0x20) != 0",
        "        self.set_odr(if v { r | 0x20 } else { r & 0xffff_ffdf })",
        // A keyword gets `_`; a read-only field has no setter.
        "    pub fn odr_in_(self) -> UInt32 {",
        // A write-only register: the rest is its reset value.
        "        const r: UInt32 = 0x100",
        "        self.set_bsrr(0x100 | (v << 16))",
        "        require v <= 0xf",
        // 8, 16 and 64 bits.
        "        unsafe { self.ptr8(0x4).read_volatile() }",
        "        self.set_dr(v)",
        "        self.set_brr((self.brr() & 0xf) | (v << 4))",
        "        require v <= 0xfff",
        "        (self.stamp() & 0xffff_ffff_0000_0000) >> 32",
        "        self.set_stamp((self.stamp() & 0xffff_ffff) | (v << 32))",
        // `dim`: CH0 and CH1, 4 bytes apart.
        "    /// CH1 (offset 0x24, 32 bits).",
        "// Not read yet: the enumerated values of CH%s.EN.",
        "// Not read yet: cluster FIFO.",
    ] {
        assert!(m.lines().any(|l| l == line), "no line `{line}` in\n{m}");
    }
    for missing in [
        "fn set_idr",
        "fn set_odr_in_",
        "fn bsrr(",
        "fn bsrr_bs5(",
        "type Gpiob",
    ] {
        assert!(!m.contains(missing), "`{missing}` in\n{m}");
    }
}

#[test]
fn a_wrong_file_says_what_is_wrong() {
    let no_base = CHIP.replace("<baseAddress>0x40004400</baseAddress>", "");
    let wide = CHIP.replace("[63:32]", "[64:32]");
    let twice = CHIP.replace("<name>IDR</name>", "<name>MODER</name>");
    for (text, said) in [
        (no_base.as_str(), "UART_1: no `<baseAddress>`"),
        (
            wide.as_str(),
            "UART_1.STAMP.HIGH: bits 32–64 don't fit a register of 64 bits",
        ),
        (twice.as_str(), "GPIOA: two parts are both named `moder`"),
        ("<chip/>", "the root element is `<chip>`, not `<device>`"),
    ] {
        assert_eq!(kavach_svd::generate(text, "x.svd").unwrap_err(), said);
    }
}
