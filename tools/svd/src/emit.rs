//! The Kavach module for a device (spec 6.5): for each peripheral a
//! constant with its address and a type made from a `Ptr<UInt8>`, with a
//! method for each register and field. Registers are read and written
//! with volatile operations; a field is masked and shifted from its
//! register.

use crate::model::{Access, Device, Field, Peripheral, Register};
use crate::names::{pascal, snake};
use std::fmt::Write;

/// The module's text; `source` names the SVD file in its first line.
pub fn module(device: &Device, source: &str) -> Result<String, String> {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by kavach svd from {source}: make it again rather than change it."
    );
    let _ = writeln!(
        out,
        "// The registers of {}, read and written with volatile operations (spec 6.5).",
        or(&device.name, "the device")
    );
    for p in &device.peripherals {
        let address = i64::try_from(p.base)
            .map_err(|_| format!("{}: address {:#x} doesn't fit an Int", p.name, p.base))?;
        let _ = writeln!(out, "\n/// {}'s base address.", p.name);
        let _ = writeln!(
            out,
            "pub const {}_address = {}",
            snake(&p.name),
            hex(address as u64)
        );
    }
    for p in &device.peripherals {
        if let Some(base) = &p.derived_from {
            if !device.peripherals.iter().any(|q| &q.name == base) {
                return Err(format!(
                    "{}: derived from `{base}`, which isn't in the file",
                    p.name
                ));
            }
            continue;
        }
        peripheral(&mut out, p, &device.peripherals)?;
    }
    Ok(out)
}

fn or<'a>(text: &'a str, otherwise: &'a str) -> &'a str {
    if text.is_empty() { otherwise } else { text }
}

/// `": description"`, or nothing when there is none. A full stop at its
/// end goes, as the line adds its own.
fn described(d: &str) -> String {
    match d.trim_end_matches('.') {
        "" => String::new(),
        d => format!(": {d}"),
    }
}

/// `n` in hex, in groups of four digits: `0x4002_0000`.
fn hex(n: u64) -> String {
    let digits = format!("{n:x}");
    let mut out = String::new();
    for (i, c) in digits.chars().enumerate() {
        if i > 0 && (digits.len() - i) % 4 == 0 {
            out.push('_');
        }
        out.push(c);
    }
    format!("0x{out}")
}

fn uint(size: u32) -> String {
    format!("UInt{size}")
}

/// The bits a register of `size` bits has set.
fn all(size: u32) -> u64 {
    if size == 64 {
        u64::MAX
    } else {
        (1 << size) - 1
    }
}

/// The text of one type, with every method name checked to be new.
struct Block<'a> {
    out: &'a mut String,
    names: Vec<String>,
    peripheral: &'a str,
}

impl Block<'_> {
    fn name(&mut self, name: String) -> Result<String, String> {
        if self.names.contains(&name) {
            return Err(format!(
                "{}: two parts are both named `{name}`",
                self.peripheral
            ));
        }
        self.names.push(name.clone());
        Ok(name)
    }

    fn line(&mut self, text: &str) {
        let _ = writeln!(self.out, "{text}");
    }
}

fn peripheral(out: &mut String, p: &Peripheral, all_of: &[Peripheral]) -> Result<(), String> {
    let ty = pascal(&p.name);
    let shared: Vec<&str> = all_of
        .iter()
        .filter(|q| q.derived_from.as_deref() == Some(p.name.as_str()))
        .map(|q| q.name.as_str())
        .collect();
    let _ = writeln!(out);
    for s in &p.skipped {
        let _ = writeln!(out, "// Not read yet: {s}.");
    }
    if !p.description.is_empty() {
        let _ = writeln!(out, "/// {}", p.description);
        let _ = writeln!(out, "///");
    }
    let mut also = String::new();
    if !shared.is_empty() {
        also = format!(" Also for {}.", shared.join(", "));
    }
    let _ = writeln!(
        out,
        "/// `{ty}.at(p)` makes it, in `unsafe`: `p` is `Ptr.at({}_address)` on the chip.{also}",
        snake(&p.name)
    );
    let _ = writeln!(out, "pub type {ty} {{\n    regs: Ptr<UInt8>\n");
    let mut b = Block {
        out,
        names: vec!["at".into(), "regs".into()],
        peripheral: &p.name,
    };
    b.line(&format!(
        "    pub fn at(regs: Ptr<UInt8>) -> {ty} {{\n        {ty}(regs: regs)\n    }}"
    ));
    let mut sizes: Vec<u32> = p.registers.iter().map(|r| r.size).collect();
    sizes.sort_unstable();
    sizes.dedup();
    for size in sizes {
        let name = b.name(format!("ptr{size}"))?;
        b.line(&format!(
            "\n    fn {name}(self, offset: Int) -> Ptr<{}> {{\n        unsafe {{ Ptr.at(self.regs.address() + offset) }}\n    }}",
            uint(size)
        ));
    }
    for r in &p.registers {
        register(&mut b, r)?;
    }
    b.line("}");
    Ok(())
}

fn register(b: &mut Block, r: &Register) -> Result<(), String> {
    let name = snake(&r.name);
    let t = uint(r.size);
    let at = format!("self.ptr{}({})", r.size, hex(r.offset));
    b.line(&format!(
        "\n    /// {}{} (offset {}, {} bits).",
        r.name,
        described(&r.description),
        hex(r.offset),
        r.size
    ));
    if r.access.reads() {
        let get = b.name(name.clone())?;
        b.line(&format!(
            "    pub fn {get}(self) -> {t} {{\n        unsafe {{ {at}.read_volatile() }}\n    }}"
        ));
    }
    if r.access.writes() {
        let set = b.name(format!("set_{name}"))?;
        if r.access.reads() {
            b.line("");
        }
        b.line(&format!(
            "    pub fn {set}(self, v: {t}) {{\n        unsafe {{ {at}.write_volatile(v) }}\n    }}"
        ));
    }
    for f in &r.fields {
        field(b, r, &name, f)?;
    }
    Ok(())
}

fn field(b: &mut Block, r: &Register, reg: &str, f: &Field) -> Result<(), String> {
    let name = format!("{reg}_{}", snake(&f.name));
    let t = uint(r.size);
    let (mask, ones) = (all(f.width) << f.lsb, all(f.width));
    let clear = all(r.size) & !mask;
    let bits = match f.width {
        1 => format!("bit {}", f.lsb),
        _ => format!("bits {}–{}", f.lsb, f.lsb + f.width - 1),
    };
    let what = described(&f.description);
    b.line(&format!("\n    /// {}.{}, {bits}{what}.", r.name, f.name));
    let gets = f.access.reads() && r.access.reads();
    let sets = f.access.writes() && r.access.writes();
    if gets {
        let get = b.name(name.clone())?;
        let body = match (f.width, f.lsb) {
            (1, _) => format!("(self.{reg}() & {}) != 0", hex(mask)),
            _ if f.width == r.size => format!("self.{reg}()"),
            (_, 0) => format!("self.{reg}() & {}", hex(mask)),
            _ => format!("(self.{reg}() & {}) >> {}", hex(mask), f.lsb),
        };
        let ty = if f.width == 1 { "Bool" } else { &t };
        b.line(&format!("    pub fn {get}(self) -> {ty} {{"));
        b.line(&format!("        {body}\n    }}"));
    }
    if !sets {
        return Ok(());
    }
    let set = b.name(format!("set_{name}"))?;
    if gets {
        b.line("");
    }
    // A write-only register can't be read: the rest of it is its reset
    // value.
    let (now, rest) = match r.access {
        Access::WriteOnly => (hex(r.reset), hex(r.reset & clear)),
        _ => (
            format!("self.{reg}()"),
            format!("(self.{reg}() & {})", hex(clear)),
        ),
    };
    if f.width == 1 {
        b.line(&format!("    pub fn {set}(self, v: Bool) {{"));
        b.line(&format!("        const r: {t} = {now}"));
        let (on, off) = (hex(mask), hex(clear));
        b.line(&format!(
            "        self.set_{reg}(if v {{ r | {on} }} else {{ r & {off} }})"
        ));
    } else if f.width == r.size {
        b.line(&format!("    pub fn {set}(self, v: {t}) {{"));
        b.line(&format!("        self.set_{reg}(v)"));
    } else {
        let shifted = match f.lsb {
            0 => "v".to_string(),
            n => format!("(v << {n})"),
        };
        b.line(&format!("    pub fn {set}(self, v: {t})"));
        b.line(&format!("        require v <= {}\n    {{", hex(ones)));
        b.line(&format!("        self.set_{reg}({rest} | {shifted})"));
    }
    b.line("    }");
    Ok(())
}
